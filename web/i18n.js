function omniLang() {
  return localStorage.getItem("omniforge_lang") || "en";
}

function omniT(key) {
  const table = OMNI_I18N[omniLang()] || OMNI_I18N.en;
  return table[key] ?? OMNI_I18N.en[key] ?? key;
}

function omniApplyLang() {
  const lang = omniLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ur" || lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = omniT(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((node) => {
    node.placeholder = omniT(node.dataset.i18nPh);
  });
  const toggle = document.getElementById("langtoggle");
  if (toggle) toggle.textContent = omniT("common.lang");
}

function omniToggleLang() {
  localStorage.setItem("omniforge_lang", omniLang() === "en" ? "hi" : "en");
  omniApplyLang();
}

window.addEventListener("DOMContentLoaded", omniApplyLang);
